// Terminal theme presets (web-term style): full 16-color ANSI palettes for
// the xterm terminal. The Settings page offers these; the selected one is
// applied to the xterm theme object in useTerminal (see terminalTheme in
// settingsStore). Curated subset of the reference app's presets — each entry
// is a real, coherent palette, kept small so it doesn't bloat the bundle.

