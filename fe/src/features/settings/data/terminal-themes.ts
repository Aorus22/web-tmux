// Look up a preset by its persisted name. Returns null for an unknown name
// (the UI falls back to the CSS-variable theme in that case).
export function getTerminalTheme(
  name: string | null | undefined,
): TerminalThemePreset | null {
  if (!name) return null
  return terminalThemes.find((t) => t.name === name) ?? null
}

// Resolve the background color for a preset name, falling back to the app's
// CSS variable when no preset is selected (or the name is unknown). Pane
// containers use this so the area behind the terminal matches the preset —
// xterm runs with allowTransparency and does not paint its own background.
export function terminalBackground(name: string | null | undefined): string {
  return getTerminalTheme(name)?.colors.background ?? 'var(--term-bg)'
}

// Relative luminance (0..1) of a hex background, using the WCAG weights.
// Used to bucket presets into dark/light for the settings filter.
export function themeLuminance(background: string): number {
  const hex = background.replace('#', '').trim()
  const full = hex.length === 3 ? [...hex].map((c) => c + c).join('') : hex
  const num = Number.parseInt(full, 16)
  if (Number.isNaN(num)) return 0.5
  const r = ((num >> 16) & 0xff) / 255
  const g = ((num >> 8) & 0xff) / 255
  const b = (num & 0xff) / 255
  const lin = (c: number) =>
    c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4)
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)
}

export function isLightTheme(preset: TerminalThemePreset): boolean {
  return themeLuminance(preset.colors.background) > 0.5
}
